#!/bin/sh
set -eu
: "${APP_DB_USER:=tournament_app}"
: "${APP_DB_PASSWORD:?APP_DB_PASSWORD must be set in .env}"

# This script runs as the PostgreSQL bootstrap administrator during first init.
# The application role is deliberately not a database or schema owner.
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 \
  --set=app_user="$APP_DB_USER" --set=app_password="$APP_DB_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE %I LOGIN PASSWORD %L', :'app_user', :'app_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'app_user')
\gexec
SELECT format('ALTER ROLE %I LOGIN PASSWORD %L', :'app_user', :'app_password')\gexec
SELECT format('GRANT CONNECT ON DATABASE %I TO %I', current_database(), :'app_user')\gexec
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM :"app_user";
GRANT USAGE ON SCHEMA public TO :"app_user";

CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(80) NOT NULL UNIQUE,
    email varchar(180) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tournaments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    team_limit integer NOT NULL CHECK (team_limit > 0),
    status varchar(30) NOT NULL CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'FINISHED'))
);

CREATE TABLE IF NOT EXISTS teams (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    captain_id bigint NOT NULL REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS team_members (
    team_id bigint NOT NULL REFERENCES teams(id),
    user_id bigint NOT NULL REFERENCES users(id),
    CONSTRAINT uq_team_members_team_user UNIQUE (team_id, user_id)
);

CREATE TABLE IF NOT EXISTS team_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    tournament_id bigint NOT NULL REFERENCES tournaments(id),
    admission_status varchar(30) NOT NULL CHECK (admission_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT uq_team_applications_team_tournament UNIQUE (team_id, tournament_id)
);

CREATE TABLE IF NOT EXISTS matches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id bigint NOT NULL REFERENCES tournaments(id),
    team1_id bigint NOT NULL REFERENCES teams(id),
    team2_id bigint NOT NULL REFERENCES teams(id),
    score1 integer NOT NULL,
    score2 integer NOT NULL,
    status varchar(30) NOT NULL CHECK (status IN ('SCHEDULED', 'FINISHED')),
    CONSTRAINT chk_match_scores_and_teams CHECK (score1 >= 0 AND score2 >= 0 AND team1_id <> team2_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE users, tournaments, teams, team_members, team_applications, matches TO :"app_user";
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO :"app_user";
SQL
